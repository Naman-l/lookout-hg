"""The README's numbers, written from the committed reports so they cannot drift.

  python -m evals.readme_block --write     replace the block between the evals markers in README.md
  python -m evals.readme_block --check     exit 1 if README.md differs from what the reports say (a test runs this)

Every number comes from evals/report.json (the answer sheet), report_gate29.json (controls run many
times), report_heldout.json, judge/calibration*.json and spend.yaml. The prose around the block states
no number.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

from . import report, spend, stats
from .run import ROOT, load_bench, load_cases

BEGIN, END = "<!-- evals:begin (generated by python -m evals.readme_block; do not edit by hand) -->", "<!-- evals:end -->"
EV = ROOT / "evals"
HBEGIN, HEND = "<!-- evals:history begin (generated by python -m evals.readme_block) -->", "<!-- evals:history end -->"


def _load(name: str) -> dict:
    return json.loads((EV / name).read_text())


def _interval(k: int, n: int) -> str:
    lo, hi = stats.wilson(k, n)
    return f"{k} of {n} [{lo:.2f}–{hi:.2f}]"


def _first_failure(r: dict) -> str:
    bad = next((t for t in report._trials(r) if t["status"] != "PASS" and t.get("detail")), None)
    return report.short((bad or r).get("detail", "")) or "failed"


def _md(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _short_why(r: dict, limit: int = 150) -> str:
    return _md(_first_failure(r))[:limit]


PROSE_CHECKS = ("buyer's words", "assumptions are really assumptions", "what would change it is specific", "answers the buyer's question", "nothing in it commits Halden")


def _counts(r: dict, phrasing=()) -> dict[str, tuple[int, int]]:
    """Per kind of check, (trials in which it held, trials) for one case; prose only counts the trials it was judged in."""
    ts = report._trials(r)
    failed = [report.trial_groups(t, phrasing) for t in ts]
    out = {g: (sum(g not in f for f in failed), len(ts)) for g in ("behaviour", "facts", "conditions")}
    judged = [i for i, t in enumerate(ts) if t.get("prose") in ("met", "failed")]
    out["prose"] = (sum("prose" not in failed[i] for i in judged), len(judged))
    return out


def _cell(held_total: tuple[int, int]) -> str:
    h, n = held_total
    return "–" if not n else f"{h} of {n}"


def what_fails(res: dict, ag: dict) -> str:
    """One line: which kinds of check the agent cases miss, and the commonest reason the prose judge gave."""
    miss = {g: [] for g in ("conditions", "facts", "prose", "behaviour")}
    reasons: dict[str, int] = {}
    for i, c in ag.items():
        r = res[i]
        phr = c.get("expected", {}).get("phrasing_terms") or []
        groups = set().union(*[report.trial_groups(t, phr) for t in report._trials(r)]) if report._trials(r) else set()
        for g in groups:
            miss[g].append(i)
        for t in report._trials(r):
            for name in PROSE_CHECKS:
                if f"{name}:" in (t.get("detail") or ""):
                    reasons[name] = reasons.get(name, 0) + 1
    n = len(ag)
    parts = []
    if miss["conditions"]:
        parts.append(f"{len(miss['conditions'])} of {n} cases leave out a condition the buyer needs stated")
    if miss["facts"]:
        parts.append(f"{len(miss['facts'])} state a number, owner or date wrongly or do not raise an unknown")
    if miss["prose"]:
        top = max(reasons, key=reasons.get) if reasons else None
        parts.append(f"{len(miss['prose'])} fail the prose judge" + (f", most often on '{top}'" if top else ""))
    if miss["behaviour"]:
        parts.append(f"{len(miss['behaviour'])} fail{'s' if len(miss['behaviour']) == 1 else ''} on what the agent did")
    return "; ".join(parts) or "no agent case misses a check"


def block() -> str:
    """The README's evaluation numbers: three lines, then one table. Every round, the sheet changes and the notes are in evals/report.md."""
    main, held = _load("report.json"), _load("report_heldout.json")
    spec, cases = load_bench(), load_cases()
    ids = report.bench_ids(spec)
    res, cfg = main["results"], main["config"]
    ctl = {i: cases[i] for i in ids["controls"] if i in res}
    ag = {i: cases[i] for i in ids["agent"] if i in res}
    live = {i: cases[i] for i in ids["live"] if i in cases and i in res}
    sysc = [res[i]["status"] == "PASS" for i in ids["system"] if i in res]
    rnd = next((r["round"] for r in reversed(yaml.safe_load((EV / "rounds.yaml").read_text()) or []) if isinstance(r.get("round"), int)), "?")
    code = [i for i, c in ctl.items() if report._kind(c) == "code"]
    model = [i for i, c in ctl.items() if report._kind(c) == "model"]
    code_held = sum(report._control_failures(res[i]) == 0 for i in code)
    model_n = sum(len(report._trials(res[i])) for i in model)
    model_bad = sum(report._control_failures(res[i]) for i in model)
    said_n = said_tot = 0
    for i in ctl:
        if any(t.get("said") is not None or report._words_only(t) for t in report._trials(res[i])):
            a_, b_ = report._control_words(res[i])
            said_n, said_tot = said_n + a_, said_tot + b_
    beh = sum(all("behaviour" not in report.trial_groups(t, c.get("expected", {}).get("phrasing_terms") or []) for t in report._trials(res[i])) for i, c in ag.items())
    full = sum(report._case_passed(res[i]) for i in ag)
    unmeasured = {k: v for k, v in report.unmeasured_facts(res, ag).items() if v}
    status = EV / "round_status.yaml"
    running = ""
    if status.exists():   # a round is running: say so in one line until its result is committed (the file is then deleted)
        st = yaml.safe_load(status.read_text()) or {}
        running = (f"**Round {st['running']} is running on the final agent;** the fixes after round {rnd} ({', '.join(st.get('fixes') or [])}) were verified live on the running app. The figures below are round {rnd}'s, and are replaced by round {st['running']}'s when it is in.")
    out = [BEGIN, "", *([running, ""] if running else []),
           f"- **Guardrails held:** code controls {code_held} of {len(code)}; model controls {model_n - model_bad} of {model_n} trials" + (f" (said it in words {said_n} of {said_tot})" if said_tot else "") + ".",
           f"- **Agent cases:** {full} of {len(ag)} passed every check in every trial; what the agent did (right contact, nothing wrongly staged) held in {beh} of {len(ag)}. {len(unmeasured)} of {len(ag)} cases have checks that could not run, because no tool returns the expected figure as a number; those are marked not measured, never counted as passes.",
           f"- **What fails, and why:** {what_fails(res, ag)}.",
           "- **How to improve it:** each failing case has one line in [`evals/report.md`](evals/report.md) (what the agent did, why, the general fix). The common thread is carry-through: the tools return the figure, date or term, and the answer leaves it out. The fix is in code that puts tool-returned figures and conditions into the answer, never a prompt line naming a case; a verifier that misreads a correct sentence is fixed the same way. The held-out sheets show whether a fix generalises.",
           "", "| Case | Kind | Passed every trial | Behaviour | Numbers, owners, dates | Conditions stated | Prose / words |", "|---|---|---|---|---|---|---|"]
    for i, c in ctl.items():
        r = res[i]
        n = len(report._trials(r))
        if r["status"] in ("BLOCKED", "SKIPPED"):
            out.append(f"| `{i}` | control, {report._kind(c)} | not run | | | | |")
            continue
        held_n = n - report._control_failures(r)
        words = _cell(report._control_words(r)) if any(t.get("said") is not None or report._words_only(t) for t in report._trials(r)) else "–"
        out.append(f"| `{i}` | control, {report._kind(c)} | {held_n} of {n} | {held_n} of {n} | – | – | {words + ' (words)' if words != '–' else '–'} |")
    for cat in report.ORDER[1:]:
        for i, c in ag.items():
            if c["category"] == cat:
                r = res[i]
                k = _counts(r, c.get("expected", {}).get("phrasing_terms") or [])
                ok = sum(t["status"] == "PASS" for t in report._trials(r))
                out.append(f"| `{i}` | {cat} | {ok} of {len(report._trials(r))} | {_cell(k['behaviour'])} | {_cell(k['facts'])} | {_cell(k['conditions'])} | {_cell(k['prose'])} |")
    for i, c in live.items():
        r = res[i]
        if r["status"] in ("BLOCKED", "SKIPPED"):
            out.append(f"| `{i}` | live finding | not run | | | | |")
            continue
        k = _counts(r)
        ok = sum(t["status"] == "PASS" for t in report._trials(r))
        out.append(f"| `{i}` | live finding | {ok} of {len(report._trials(r))} | {_cell(k['behaviour'])} | {_cell(k['facts'])} | {_cell(k['conditions'])} | – |")
    hres = {i: r for i, r in held["results"].items() if not i.startswith("_")}
    out += ["", *_bench_vs_heldout(res, ag, hres)]
    out += ["", f"Round {rnd}, {cfg['date']}, agent at git `{cfg['git_sha']}`: how to read the table and where the notes on every cell are is in [`evals/README.md`](evals/README.md).", "",
            "Every round, the sheet changes and their reasons, the corrections and the answers behind each cell: [`evals/report.md`](evals/report.md), [`evals/report.html`](evals/report.html), [`evals/README.md`](evals/README.md). Live end-to-end runs of every workflow, checked by hand against the raw files: [`evals/E2E-REPORT.md`](evals/E2E-REPORT.md).", "", END]
    return "\n".join(out)


def _bench_vs_heldout(res: dict, ag: dict, hres: dict) -> list[str]:
    """The overfitting check: the same kinds of check on the bench's agent cases and on the held-out sheets, which were written apart from the cases the builders saw."""
    from . import run as _run
    hcases = _run.load_cases(directory=_run.HELDOUT)

    def counts(results: dict, cases: dict) -> dict[str, str]:
        ks = {i: _counts(r, cases.get(i, {}).get("expected", {}).get("phrasing_terms") or []) for i, r in results.items() if i in cases and r.get("status") not in ("BLOCKED", "SKIPPED")}
        n = len(ks)
        pick = lambda g: sum(1 for k in ks.values() if k[g][1] and k[g][0] == k[g][1])   # noqa: E731
        full = sum(1 for i, r in results.items() if i in ks and report._case_passed(r))
        return {"n": str(n), "all": f"{full} of {n}", **{g: f"{pick(g)} of {n}" for g in ("behaviour", "facts", "conditions", "prose")}}

    bench, held = counts({i: res[i] for i in ag}, ag), counts(hres, hcases)
    rows = [("Passed every check in every trial", "all"), ("Behaviour held in every trial", "behaviour"), ("Numbers, owners, dates right in every trial", "facts"),
            ("Conditions the buyer needs stated, in every trial", "conditions"), ("Prose met in every trial", "prose")]
    return ["**Bench versus held-out.** The held-out sheets were written apart from the cases the builders saw and are run on the same agent, so a bench that rises while the held-out set does not would mean the agent was fitted to the bench. The held-out sheets check figures more loosely than the bench (many bench facts are compared by tool number id), so read their numbers row as the easier test.", "",
            f"| Agent cases that held, over every trial | Bench ({bench['n']} cases) | Held-out ({held['n']} sheets that ran) |", "|---|---|---|",
            *[f"| {name} | {bench[k]} | {held[k]} |" for name, k in rows]]


def note() -> str:
    """How to read the README table, moved here from the README block: the trial counts, the live findings, the held-out run, the calibration and the spend."""
    main, held = _load("report.json"), _load("report_heldout.json")
    spec = load_bench()
    ids = report.bench_ids(spec)
    res, cfg = main["results"], main["config"]
    sysc = [res[i]["status"] == "PASS" for i in ids["system"] if i in res]
    hres = {i: r for i, r in held["results"].items() if not i.startswith("_")}
    hp = sum(report._case_passed(r) for r in hres.values())
    return (f"**Reading the README table.** Round, {cfg['date']}, agent at git `{cfg['git_sha']}`, sheets `{cfg.get('sheets_hash', '?')}`. Each cell is the number of trials in which that kind of check held, "
            f"over the case's own trials (2, or 3 for controls; the live findings run once); live single runs vary. "
            f"The answer sheet is {len(ids['controls']) + len(ids['agent'])} cases; the {len(ids['live'])} live findings were written after live use found those failures and are graded on behaviour; {sum(sysc)} of {len(sysc)} system checks pass. "
            f"Held out (sheets written apart): {hp} of {len(hres)} passed every trial, on the agent at git `{held['config']['git_sha']}`. "
            "The judge and the Reviewer are calibrated against a model's labels only; no person has labelled them yet. "
            f"{spend.line().split(' (the CLI')[0]}.")


def history() -> str:
    return HBEGIN + "\n\n" + note() + "\n\n" + report.rounds_table(EV / "rounds.yaml") + "\n\n" + HEND


def apply(readme: str, new: str, begin: str = BEGIN, end: str = END) -> str:
    a, b = readme.index(begin), readme.index(end) + len(end)
    return readme[:a] + new + readme[b:]


def main(argv: list[str] | None = None) -> int:
    mode = (argv or sys.argv[1:] or ["--check"])[0]
    targets = [(ROOT / "README.md", block(), BEGIN, END), (EV / "README.md", history(), HBEGIN, HEND)]
    stale = False
    for path, text, b, e in targets:
        cur = path.read_text()
        want = apply(cur, text, b, e)
        if mode == "--write":
            path.write_text(want)
        elif want != cur:
            print(f"{path.relative_to(ROOT)} is not what the reports say: run python -m evals.readme_block --write", file=sys.stderr)
            stale = True
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
