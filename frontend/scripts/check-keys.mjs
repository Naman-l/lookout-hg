// Keyboard: j/k move between Today's rows and Enter opens one; Escape closes a filter menu; More's rows open HG pages. Needs `make run`.
import { chromium } from "playwright-core";
const BASE = process.env.BASE ?? "http://127.0.0.1:8001";
const browser = await chromium.launch({ channel: "chrome" });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
await ctx.addInitScript(() => { localStorage.setItem("lookout.me", "Sambhav Kumar"); });
const page = await ctx.newPage();
await page.route("**/*", (r) => (["GET", "HEAD"].includes(r.request().method()) ? r.continue() : r.abort()));
const fails = [];
await page.goto(BASE + "/", { waitUntil: "networkidle" });
await page.keyboard.press("j"); await page.keyboard.press("j");
const focused = await page.evaluate(() => document.activeElement?.className ?? "");
if (!focused.includes("td-row")) fails.push(`j did not move to a row (${focused})`);
await page.keyboard.press("Enter"); await page.waitForURL(/\/items\//, { timeout: 5000 }).catch(() => fails.push("Enter did not open the row"));
await page.goto(BASE + "/", { waitUntil: "networkidle" });
await page.getByRole("button", { name: "Act by" }).click();
await page.keyboard.press("Escape");
if (await page.getByRole("menu").count()) fails.push("Escape did not close the Act by menu");
const pc = await browser.newContext({ viewport: { width: 390, height: 844 } });
const p2 = await pc.newPage();
await p2.goto(BASE + "/more", { waitUntil: "networkidle" });
const hrefs = await p2.locator(".nav-row").evaluateAll((es) => es.map((e) => e.getAttribute("href")));
if (!hrefs.includes("/lookup") || !hrefs.includes("/prs")) fails.push(`More lacks the HG pages: ${hrefs.join(" ")}`);
await browser.close();
console.log(fails.length ? fails.join("\n") : "ok: j/k and Enter on Today, Escape closes a menu, More opens HG pages");
process.exit(fails.length ? 1 : 0);
